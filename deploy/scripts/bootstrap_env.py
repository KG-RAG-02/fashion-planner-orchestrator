#!/usr/bin/env python3
"""Create or complete the deployment env file without ever printing a secret value.

Default target: ~/.config/vogue/vogue.env (outside the iCloud-synced project folder, mode 0600).

* Generates a fresh FASHION_PLANNER_SERVICE_TOKEN and NEO4J_STUB_PASSWORD (never reuses old tokens).
* Copies Cloudflare R2 and OpenAI values from the sibling service .env files when they exist
  (new-product-agent/.env, then sales-market-agent/.env) — values are read, never echoed.
* Leaves NEO4J_URI / NEO4J_USER / NEO4J_PASSWORD empty for the operator to fill (Neo4j Aura).
* Re-running only adds missing keys; existing values (e.g. your Aura credentials) are never overwritten
  unless --force is given.

Prints key names with set/empty status only.
"""
from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

DEPLOY = Path(__file__).resolve().parents[1]
WORKSPACE = DEPLOY.parents[1]  # .../VOGUE (sibling repos live here)
DEFAULT_TARGET = Path.home() / ".config" / "vogue" / "vogue.env"
SOURCES = (WORKSPACE / "new-product-agent" / ".env", WORKSPACE / "sales-market-agent" / ".env")

# (key, origin, default) — origin: "generate" | "copy:<SOURCE_KEY>" | "blank" | "default"
LAYOUT = (
    ("# --- every profile -------------------------------------------------------", None, None),
    ("FASHION_PLANNER_SERVICE_TOKEN", "generate", None),
    ("NEO4J_STUB_PASSWORD", "generate", None),
    ("# --- data profile (rehearsal, live): Cloudflare R2, copied from the service .env files ---", None, None),
    ("R2_ACCOUNT_ID", "copy:R2_ACCOUNT_ID", None),
    ("R2_BUCKET", "copy:R2_BUCKET", None),
    ("R2_ACCESS_KEY_ID", "copy:R2_ACCESS_KEY_ID", None),
    ("R2_SECRET_ACCESS_KEY", "copy:R2_SECRET_ACCESS_KEY", None),
    ("R2_ENDPOINT", "copy:R2_ENDPOINT", None),
    ("R2_DB_KEY", "copy:R2_DB_KEY", None),
    ("RESEARCH_AGGREGATE_SNAPSHOT_KEY", "copy:RESEARCH_AGGREGATE_SNAPSHOT_KEY", None),
    ("R2_IMAGE_PREFIX", "copy:R2_IMAGE_PREFIX", None),
    ("# --- data profile: Neo4j Aura for the trend graph (fill these in yourself) ---", None, None),
    ("NEO4J_URI", "blank", None),
    ("NEO4J_USER", "blank", None),
    ("NEO4J_PASSWORD", "blank", None),
    ("# --- paid profile (live only): OpenAI ---", None, None),
    ("FASHION_PLANNER_OPENAI_API_KEY", "copy:LLM_API_KEY", None),
    ("FASHION_PLANNER_ORCHESTRATOR_LLM_MODEL", "default", "gpt-4o-mini"),
    ("FASHION_PLANNER_NOVELTY_IMAGE_MODEL", "blank", None),
)


def parse_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.removeprefix("export ").strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path(os.environ.get("FASHION_PLANNER_ENV_FILE", DEFAULT_TARGET)))
    parser.add_argument("--force", action="store_true", help="regenerate tokens and recopy values (keeps nothing)")
    args = parser.parse_args(argv)

    existing = {} if args.force else parse_env(args.out)
    sources: dict[str, str] = {}
    for path in reversed(SOURCES):  # first listed source wins
        sources.update({k: v for k, v in parse_env(path).items() if v})

    lines, report = [], []
    for key, origin, default in LAYOUT:
        if origin is None:
            lines.append(key)
            continue
        value = existing.get(key, "")
        if not value:
            if origin == "generate":
                value = secrets.token_urlsafe(48)
            elif origin.startswith("copy:"):
                value = sources.get(origin.split(":", 1)[1], "")
            elif origin == "default":
                value = default or ""
        lines.append(f"{key}={value}")
        report.append((key, "set" if value else "EMPTY", origin))
    extra = {k: v for k, v in existing.items() if k not in {row[0] for row in LAYOUT if row[1]}}
    if extra:
        lines.append("# --- kept from the previous file ---")
        lines.extend(f"{k}={v}" for k, v in extra.items())

    args.out.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(args.out.parent, 0o700)
    tmp = args.out.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write("# VOGUE deployment env — generated by deploy/bin/vogue init-env. Never commit or print.\n")
        handle.write("\n".join(lines) + "\n")
    os.replace(tmp, args.out)
    os.chmod(args.out, 0o600)

    print(f"env file: {args.out} (mode 600)")
    for key, status, origin in report:
        print(f"  {key:34s} {status:6s} ({origin})")
    missing_aura = [k for k, s, _ in report if k.startswith("NEO4J_") and k != "NEO4J_STUB_PASSWORD" and s == "EMPTY"]
    if missing_aura:
        print("  -> rehearsal/live need Neo4j Aura: fill " + ", ".join(missing_aura) + " in the file above.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
